import { z } from 'zod';

/**
 * `gitignore.render`, the pure half (video-structure plan §4D; design: brains `video-as-code/
 * video-gitignore-central-owner.md` §2–3). One generated block owns the ignore rules of every `v-*` brand repo, so the
 * seven hand-edited copies stop drifting. This file holds the rules and the text work and touches no disk, no clock and
 * no machine: the block is a pure function of (base version, brand key, overlay), byte-identical on every Mac (R8).
 * `gitignore.ts` reads and writes the files.
 *
 * Design notes where this departs from the design doc:
 *  - git has no trailing comments (`pattern # why` is one pattern), so a reason tag heads each group as a comment line
 *    instead of trailing each rule.
 *  - Order inside the block is fixed: the denies, then the base re-includes (`!`), then the few denies that must beat a
 *    re-include (machine-local files that are JSON), then the brand overlay in the order its file gives. `-trash/` and
 *    `-renders/` are directory rules, so no file re-include can reach inside them.
 */

/** Bump when the base rules change. The marker carries it, so a Mac on older rules shows as drift, not a silent rewrite. */
export const GITIGNORE_BASE_VERSION = 1;

export const GITIGNORE_BEGIN = '# >>> BEGIN generated by fli gitignore.render';
export const GITIGNORE_END = '# <<< END generated';

const Tag = z.string().regex(/^[A-Z][A-Z0-9-]*$/, 'a reason tag is UPPER-KEBAB (DAMIT-MASTER)');
const OneLine = (what: string) =>
  z.string().refine((value) => !/[\r\n]/.test(value), `${what} must be one line`);

/**
 * One ignore pattern. No leading or trailing space (git trims trailing space, so it would not match what it says), no
 * newline, and not a comment (a leading `#` would be one: escape it `\#`).
 */
export const GitignorePattern = OneLine('a pattern')
  .refine((p) => p.length > 0, 'a pattern is not empty')
  .refine((p) => p === p.trim(), 'a pattern has no leading or trailing space')
  .refine((p) => !p.startsWith('#'), 'a pattern starting with # is a comment; write \\#');

/** A brand's own rule, kept in its `fli.brand.json` (`gitignore: [...]`) so it travels with the repo. */
export const GitignoreOverlayRule = z.object({
  pattern: GitignorePattern,
  reason: Tag,
  note: OneLine('a note').optional(),
});
export type GitignoreOverlayRule = z.infer<typeof GitignoreOverlayRule>;

export const GitignoreGroup = z.object({
  reason: Tag,
  note: z.string(),
  patterns: z.array(z.string()),
});
export type GitignoreGroup = z.infer<typeof GitignoreGroup>;

