/** Every pattern line the base and an overlay would emit, for duplicate detection. */
function groupsFor(overlay: readonly GitignoreOverlayRule[]): GitignoreGroup[] {
  const groups: GitignoreGroup[] = [...GITIGNORE_BASE];
  // Consecutive rules with one reason and note share a header, in the order the brand wrote them.
  for (const rule of overlay) {
    const last = groups[groups.length - 1];
    const note = rule.note ?? '';
    if (
      groups.length > GITIGNORE_BASE.length &&
      last &&
      last.reason === rule.reason &&
      last.note === note
    ) {
      groups[groups.length - 1] = { ...last, patterns: [...last.patterns, rule.pattern] };
    } else groups.push({ reason: rule.reason, note, patterns: [rule.pattern] });
  }
  return groups;
}

export interface GitignoreRenderOptions {
  /** The brand key (`aitldr`), as in `fli.brand.json`. Named in the marker; no path, host or user ever is. */
  brand: string;
  overlay?: readonly GitignoreOverlayRule[];
}

/**
 * The generated block, `BEGIN … END`, LF line endings, ending with a newline. Throws on an invalid overlay rule or a
 * brand key with a newline.
 */
export function renderGitignoreBlock(options: GitignoreRenderOptions): string {
  const overlay = z.array(GitignoreOverlayRule).parse(options.overlay ?? []);
  const brand = OneLine('brand').parse(options.brand);
  const lines = [
    `${GITIGNORE_BEGIN} (base v${GITIGNORE_BASE_VERSION}, brand ${brand}) - DO NOT EDIT BETWEEN THE MARKERS`,
    '# Change the rules in fli-core (base) or in this brand\'s fli.brand.json "gitignore" (overlay), then re-render.',
  ];
  for (const group of groupsFor(overlay)) {
    lines.push('', group.note === '' ? `# [${group.reason}]` : `# [${group.reason}] ${group.note}`);
    lines.push(...group.patterns);
  }
  lines.push(GITIGNORE_END, '');
  return lines.join('\n');
}

/** The pattern lines (not comments) of a block's text. */
export function patternLines(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .filter((line) => line !== '' && !line.startsWith('#'));
}

interface Located {
  /** Offset of the BEGIN line's first character. */
  start: number;
  /** Offset just past the END line's newline (or the end of the file). */
  end: number;
}

export type BlockLocation =
  { kind: 'none' } | { kind: 'broken'; message: string } | ({ kind: 'found' } & Located);

/** Find the one generated block. Two BEGINs, a BEGIN with no END, an END with no BEGIN, or END before BEGIN: `broken`. */
export function locateBlock(text: string): BlockLocation {
  const begins: number[] = [];
  const ends: { start: number; end: number }[] = [];
  let offset = 0;
  while (offset <= text.length) {
    const nl = text.indexOf('\n', offset);
    const stop = nl === -1 ? text.length : nl + 1;
    const line = text.slice(offset, nl === -1 ? text.length : nl).replace(/\r$/, '');
    if (line.startsWith(GITIGNORE_BEGIN)) begins.push(offset);
    else if (line === GITIGNORE_END) ends.push({ start: offset, end: stop });
    if (nl === -1) break;
    offset = stop;
  }
  if (begins.length === 0 && ends.length === 0) return { kind: 'none' };
  if (begins.length > 1)
    return { kind: 'broken', message: `${begins.length} BEGIN markers (expected 1)` };
  if (ends.length > 1)
    return { kind: 'broken', message: `${ends.length} END markers (expected 1)` };
  if (begins.length === 0) return { kind: 'broken', message: 'an END marker with no BEGIN' };
  if (ends.length === 0) return { kind: 'broken', message: 'a BEGIN marker with no END' };
  const begin = begins[0] as number;
  const end = ends[0] as { start: number; end: number };
  if (end.start < begin)
    return { kind: 'broken', message: 'the END marker comes before the BEGIN' };
  return { kind: 'found', start: begin, end: end.end };
}

/** The base version a block's marker names, or null (an older or hand-made marker). */
export function markerVersion(blockText: string): number | null {
  const match = /\(base v(\d+),/.exec(blockText.split(/\r?\n/, 1)[0] ?? '');
  return match ? Number(match[1]) : null;
}

export const GitignoreRenderResult = z.object({
  status: z.enum(['created', 'updated', 'unchanged', 'refused']),
  /** The whole file after the render (the existing text, untouched, when refused). */
  content: z.string(),
  /** Lines in the new block that were not in the old one. */
  added: z.array(z.string()),
  /** Lines in the old block that are not in the new one. */
  removed: z.array(z.string()),
  /** Hand-written pattern lines outside the block that the block now also emits: reported, never deleted. */
  legacyDuplicates: z.array(z.string()),
  /** The block is not the last thing in the file: a hand rule after it could undo a re-include. Reported, not moved. */
  blockNotLast: z.boolean(),
  /** Why a render was refused: the markers are broken. */
  message: z.string().optional(),
});
export type GitignoreRenderResult = z.infer<typeof GitignoreRenderResult>;

function lineDiff(before: string, after: string): { added: string[]; removed: string[] } {
  const count = new Map<string, number>();
  for (const line of before.split('\n')) count.set(line, (count.get(line) ?? 0) + 1);
  const added: string[] = [];
  for (const line of after.split('\n')) {
    const n = count.get(line) ?? 0;
    if (n > 0) count.set(line, n - 1);
    else added.push(line);
  }
  const removed: string[] = [];
  for (const [line, n] of count) for (let i = 0; i < n; i += 1) removed.push(line);
  const keep = (l: string) => l.trim() !== '';
  return { added: added.filter(keep), removed: removed.filter(keep) };
}

function handLines(
  text: string,
  block: Located | null,
): { dupes: (generated: Set<string>) => string[]; notLast: boolean } {
  const outside = block === null ? text : text.slice(0, block.start) + text.slice(block.end);
  const after = block === null ? '' : text.slice(block.end);
  return {
    notLast: patternLines(after).length > 0,
    dupes: (generated) => [...new Set(patternLines(outside).filter((line) => generated.has(line)))],
  };
}

/**
 * Render the block into a `.gitignore`'s text. `existing` is the file as it is (`null`/`''` when there is none).
 *   - No block yet: the block is appended at the end after a blank line; hand lines are kept as they are and any that
 *     the block now also emits are listed in `legacyDuplicates` (never deleted without a person's say).
 *   - A block: replaced in place; every byte outside the markers is untouched.
 *   - Broken markers (two BEGINs, no END…): `refused`, nothing changes.
 * Deterministic and idempotent: rendering its own output returns `unchanged`.
 */
export function renderGitignore(
  existing: string | null,
  options: GitignoreRenderOptions,
): GitignoreRenderResult {
  const text = existing ?? '';
  const block = renderGitignoreBlock(options);
  const located = locateBlock(text);
  if (located.kind === 'broken') {
    return {
      status: 'refused',
      content: text,
      added: [],
      removed: [],
      legacyDuplicates: [],
      blockNotLast: false,
      message: `The generated block is damaged (${located.message}); fix it by hand first. Nothing was written.`,
    };
  }
  const generated = new Set(patternLines(block));
  if (located.kind === 'found') {
    const content = text.slice(0, located.start) + block + text.slice(located.end);
    const hand = handLines(text, located);
    const diff = lineDiff(text.slice(located.start, located.end), block);
    return {
      status: content === text ? 'unchanged' : 'updated',
      content,
      added: diff.added,
      removed: diff.removed,
      legacyDuplicates: hand.dupes(generated),
      blockNotLast: hand.notLast,
    };
  }
  const head = text === '' ? '' : `${text.endsWith('\n') ? text : `${text}\n`}\n`;
  const hand = handLines(text, null);
  return {
    status: text === '' && existing === null ? 'created' : 'updated',
    content: head + block,
    added: block.split('\n').filter((l) => l.trim() !== ''),
    removed: [],
    legacyDuplicates: hand.dupes(generated),
    blockNotLast: false,
  };
}

export const GitignoreCheckResult = z.object({
  /** `ok`: the block is what would be rendered. `drift`: it differs. `no-block`: never generated. `broken-markers`. */
  status: z.enum(['ok', 'drift', 'no-block', 'broken-markers']),
  /** `status === 'ok'`: the exit code of a hook or a fleet sweep is non-zero for everything else. */
  ok: z.boolean(),
  /** Lines the rendered block has that the file's does not. */
  missing: z.array(z.string()),
  /** Lines the file's block has that the rendered one does not (someone edited between the markers). */
  extra: z.array(z.string()),
  /** The base version in the file's marker, when there is one. */
  fileBaseVersion: z.number().int().nullable(),
  baseVersion: z.number().int(),
  /** Why, in a sentence, when not ok. */
  reason: z.string().optional(),
  legacyDuplicates: z.array(z.string()),
  blockNotLast: z.boolean(),
});
export type GitignoreCheckResult = z.infer<typeof GitignoreCheckResult>;

/**
 * `gitignore.render --check`: write nothing, say whether the file's block is what would be rendered. A different base
 * version is drift with that reason — never a rewrite on the spot (design §2.6: update the committed file where the
 * rules are made and let the other Mac pull).
 */
export function checkGitignore(
  existing: string | null,
  options: GitignoreRenderOptions,
): GitignoreCheckResult {
  const text = existing ?? '';
  const block = renderGitignoreBlock(options);
  const located = locateBlock(text);
  const base = {
    baseVersion: GITIGNORE_BASE_VERSION,
    missing: [] as string[],
    extra: [] as string[],
    fileBaseVersion: null as number | null,
    legacyDuplicates: [] as string[],
    blockNotLast: false,
  };
  if (located.kind === 'broken') {
    return {
      ...base,
      status: 'broken-markers',
      ok: false,
      reason: `The generated block is damaged (${located.message}).`,
    };
  }
  const generated = new Set(patternLines(block));
  const hand = handLines(text, located.kind === 'found' ? located : null);
  const legacyDuplicates = hand.dupes(generated);
  if (located.kind === 'none') {
    return {
      ...base,
      status: 'no-block',
      ok: false,
      reason: 'This .gitignore has never been generated.',
      legacyDuplicates,
    };
  }
  const actual = text.slice(located.start, located.end);
  const fileBaseVersion = markerVersion(actual);
  if (actual === block) {
    return {
      ...base,
      status: 'ok',
      ok: true,
      fileBaseVersion,
      legacyDuplicates,
      blockNotLast: hand.notLast,
    };
  }
  const diff = lineDiff(actual, block);
  const reason =
    fileBaseVersion !== GITIGNORE_BASE_VERSION
      ? `base version differs (file v${fileBaseVersion ?? '?'}, rules v${GITIGNORE_BASE_VERSION})`
      : diff.added.length === 0 && diff.removed.length === 0
        ? 'the block differs in line endings or marker text'
        : 'someone edited between the markers, or the overlay changed';
  return {
    ...base,
    status: 'drift',
    ok: false,
    reason,
    missing: diff.added,
    extra: diff.removed,
    fileBaseVersion,
    legacyDuplicates,
    blockNotLast: hand.notLast,
  };
}
